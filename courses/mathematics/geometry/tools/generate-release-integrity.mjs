import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT=path.resolve('courses/mathematics/geometry');
const EXCLUDE_HASH=new Set(['FILE_MANIFEST.md','SHA256SUMS.txt','VALIDATION_REPORT.md']);
const args=process.argv.slice(2);
const check=args.includes('--check');
const oi=args.indexOf('--output');
const output=oi>=0?path.resolve(args[oi+1]||''):null;

function walk(dir){
 const out=[];
 for(const ent of fs.readdirSync(dir,{withFileTypes:true})){
  const p=path.join(dir,ent.name);
  if(ent.isDirectory())out.push(...walk(p));else out.push(p);
 }
 return out;
}
const rel=p=>path.relative(ROOT,p).split(path.sep).join('/');
const paths=walk(ROOT).map(rel).sort((a,b)=>a.localeCompare(b));
const manifest=['# Geometry File Manifest','','Generated by `tools/generate-release-integrity.mjs`.','',`Total files: ${paths.length}`,'',...paths.map(p=>`- \`${p}\``),''].join('\n');
const hashed=paths.filter(p=>!EXCLUDE_HASH.has(p));
const sums=['# Geometry SHA-256 Release Integrity','# Generated by tools/generate-release-integrity.mjs','# Excluded mutable release metadata: FILE_MANIFEST.md, SHA256SUMS.txt, VALIDATION_REPORT.md','',...hashed.map(p=>`${crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT,p))).digest('hex')}  ${p}`),''].join('\n');

if(output){
 fs.mkdirSync(output,{recursive:true});
 fs.writeFileSync(path.join(output,'FILE_MANIFEST.md'),manifest);
 fs.writeFileSync(path.join(output,'SHA256SUMS.txt'),sums);
 console.log(`Generated release integrity files in ${output}`);
}
if(check){
 const checks=[['FILE_MANIFEST.md',manifest],['SHA256SUMS.txt',sums]];
 let bad=false;
 for(const [name,expected] of checks){
  const file=path.join(ROOT,name),actual=fs.existsSync(file)?fs.readFileSync(file,'utf8'):'';
  if(actual!==expected){console.error(`${name} is stale; regenerate release integrity metadata.`);bad=true}else console.log(`OK ${name}`);
 }
 if(bad)process.exit(1);
}
if(!output&&!check){
 console.error('Use --output <directory> to generate files or --check to verify canonical metadata.');
 process.exit(2);
}
