const NEVER_CACHE=/(?:^|\/)(?:teacher|teacher-keys)(?:\/|$)/i;
function shouldNeverCache(url){return NEVER_CACHE.test(url.pathname)}


const MISSION_OFFLINE_RELEASE="ams-v1.7.0-recovery-popout-r1-20261015";
