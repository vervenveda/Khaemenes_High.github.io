import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const root="courses/mathematics/pre-algebra/";
const html=fs.readFileSync(root+"index.html","utf8");
const scripts=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)].filter(m=>!/\bsrc\s*=/.test(m[1]));
assert.equal(scripts.length,2,"landing page inline scripts must not be prematurely closed");
for(const [i,m] of scripts.entries())new vm.Script(m[2],{filename:"prealgebra-index-inline-"+i});
const report=html.slice(html.indexOf("function reportHTML(){"),html.indexOf("function printReport(){"));
assert.ok(report.includes("function reportHTML()"));
assert.ok(!report.includes("<script"),"print export should have no external script");
const map=JSON.parse(fs.readFileSync(root+"course-map.json","utf8"));
const docs=fs.readFileSync(root+"README.md","utf8");
assert.equal(map.units.find(u=>u.number===1).weeks,3);
assert.equal(map.units.find(u=>u.number===13).weeks,1);
assert.ok(docs.includes("## Unit 01 — Number Systems, Factors & Estimation\n**3 weeks**"));
assert.ok(docs.includes("## Unit 13 — Mathematical Modelling Capstone\n**1 week**"));
const src=fs.readFileSync(root+"assets/prealgebra-archaemenes-upgrade.js","utf8");
const start=src.indexOf("function migrateLegacyDiagnosticWeek(){");
const end=src.indexOf("function patchPlacementArchitecture(){",start);
assert.ok(start>=0&&end>start);
function migrate(weeks){
 const state={students:[{id:"existing",progress:{weeks}}]};
 let saved=0;
 const context=vm.createContext({courseState:()=>state,persistCourseState:()=>saved++,Date,JSON});
 vm.runInContext(src.slice(start,end)+"\nmigrateLegacyDiagnosticWeek();",context);
 return {progress:state.students[0].progress,saved};
}
const important={1:{quiz:{best:94},lessons:{Monday:true}},2:{quiz:{best:88}}};
const keep=migrate(important);
assert.equal(keep.progress.weeks[1].quiz.best,94);
assert.equal(keep.progress.placementWeekMigrationStatus,"manual-review-required-week1-provenance");
assert.equal(keep.progress.placement.legacyDiagnosticWeekRecord,undefined);
assert.equal(keep.saved,1);
const move=migrate({1:{unitId:"u00",quiz:{best:72}}});
assert.equal(move.progress.weeks[1],undefined);
assert.equal(move.progress.placement.legacyDiagnosticWeekRecord.quiz.best,72);
assert.equal(move.progress.placementWeekMigrationStatus,"explicit-diagnostic-migrated");
console.log("PASS Pre-Algebra entry script, canonical 36-week map, non-destructive Week 1 migration.");
