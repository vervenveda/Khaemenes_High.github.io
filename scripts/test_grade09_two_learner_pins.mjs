import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const source=fs.readFileSync("courses/shared/high-school-course-pins.js","utf8");
const store=new Map();
const storage={getItem:k=>store.has(k)?store.get(k):null,setItem:(k,v)=>store.set(k,String(v)),removeItem:k=>store.delete(k)};
const context={window:{localStorage:storage,dispatchEvent:()=>{}},CustomEvent:class{constructor(type,opts){this.type=type;this.detail=opts.detail}},Date,JSON,encodeURIComponent};
vm.runInNewContext(source,context);
const pins=context.window.KhaemenesHighCoursePins;
const active="khaemenes_active_learner_v1",family="khaemenes_family_registry_v1";
store.set(family,JSON.stringify({learners:{studentA:{learnerId:"studentA"},studentB:{learnerId:"studentB"}}}));
const switchTo=id=>store.set(active,JSON.stringify(id));
switchTo("studentA");
assert.equal(pins.activeLearner(),"studentA");
assert.equal(pins.writePins(["pre-algebra","english-9","world-language-9-french"]),true);
assert.equal(pins.writeLanguageChoices({"9":"french"}),true);
switchTo("studentB");
assert.equal(pins.activeLearner(),"studentB");
assert.equal(pins.readPins().length,0,"Second learner inherited first learner pins");
assert.equal(Object.keys(pins.readLanguageChoices()).length,0,"Second learner inherited first learner language");
assert.equal(pins.writePins(["algebra-1","integrated-science-9","world-language-9-spanish"]),true);
assert.equal(pins.writeLanguageChoices({"9":"spanish"}),true);
switchTo("studentA");
assert.equal(pins.readPins().join(","),"pre-algebra,english-9,world-language-9-french");
assert.equal(pins.readLanguageChoices()["9"],"french");
switchTo("studentB");
assert.equal(pins.readPins().join(","),"algebra-1,integrated-science-9,world-language-9-spanish");
assert.equal(pins.readLanguageChoices()["9"],"spanish");
const academy=JSON.parse(store.get(pins.ACADEMY_PIN_KEY));
assert.ok(academy.learners.studentA.some(x=>x.id==="pre-algebra"));
assert.ok(academy.learners.studentB.some(x=>x.id==="algebra-1"));
assert.ok(!academy.learners.studentA.some(x=>x.id==="algebra-1"),"Academy pin mirror mixed learners");
assert.ok(!academy.learners.studentB.some(x=>x.id==="pre-algebra"),"Academy pin mirror mixed learners");
switchTo("studentA");assert.equal(pins.writePins(["english-9"]),true);
assert.equal(pins.readPins().join(","),"english-9","Unpin was resurrected by Academy pin mirror");
switchTo("studentB");assert.ok(pins.readPins().includes("algebra-1"),"One learner's unpin changed another's pins");
console.log("PASS: two-learner Grade 9 pins, language selections, Academy mirror and unpin isolation");
