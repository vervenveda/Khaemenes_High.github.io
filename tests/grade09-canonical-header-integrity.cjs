"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const html=fs.readFileSync(path.join(root,"grades/grade-09/index.html"),"utf8");
const nav=fs.readFileSync(path.join(root,"assets/high-navigation-v1.js"),"utf8");
assert.equal((html.match(/<header\b[^>]*data-khae-header/g)||[]).length,1,"One canonical header only");
assert.match(html,/<span data-khae-brand-mark>K<\/span>/,"Academy header mark must be K");
assert.match(html,/<body\b[^>]*data-high-hide-breadcrumbs="true"/,"No legacy page-local breadcrumb");
assert.match(html,/<body\b[^>]*data-high-header-breadcrumbs="true"/,"Shared breadcrumb generation must be opted in");
assert.doesNotMatch(html,/<nav\b[^>]*class="breadcrumbs"/,"Do not restore legacy breadcrumb markup");
assert.match(nav,/dataset\.highHideBreadcrumbs==="true"/,"Old breadcrumb generator respects suppression");
assert.match(nav,/dataset\.highHeaderBreadcrumbs!=="true"/,"Shared header breadcrumb is opt-in");
assert.match(nav,/header\.querySelector\("\[data-khae-breadcrumb-row\]"\)/,"Header breadcrumb must be idempotent");
assert.match(nav,/header\.appendChild\(row\)/,"Breadcrumb belongs inside one canonical header");
assert.match(nav,/14px\/1\.5 Nunito/,"Breadcrumb font must be Nunito at 14px");
assert.match(nav,/text-align:left;color:#243038/,"Breadcrumb is left-aligned with readable charcoal contrast");
assert.match(html,/href="student-profile\/"/,"Dashboard route retained");
assert.match(html,/href="student-profile\/daily-lessons\/"/,"Daily lessons route retained");
assert.match(html,/href="student-profile\/grades\/"/,"Grades route retained");
assert.match(html,/href="student-profile\/games\/"/,"Games route retained");
new vm.Script(nav,{filename:"high-navigation-v1.js"});
const inline=[...html.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)];
for(const [i,m] of inline.entries())new vm.Script(m[1],{filename:"grade09-inline-"+i+".js"});
assert.ok(inline.length>=3,"Inline source integrity must be checked");
console.log("PASS: Grade 09 K header, Nunito breadcrumb, suppressed legacy trail, linked destinations, JS syntax");
