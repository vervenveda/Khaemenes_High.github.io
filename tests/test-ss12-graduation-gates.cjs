#!/usr/bin/env node
"use strict";
const fs=require("node:fs"),path=require("node:path"),vm=require("node:vm"),assert=require("node:assert/strict");
const html=fs.readFileSync(path.join(__dirname,"../courses/social-studies/grade-12/index.html"),"utf8");
const start=html.indexOf("const APP = "),end=html.indexOf(";\n",start);
assert(start>=0&&end>start);
const APP=JSON.parse(html.slice(start+12,end));
const a=html.indexOf("function ensure(s){"),b=html.indexOf("/* 4. Render router */",a);
assert(a>=0&&b>a,"Expected gradebook helpers/gates");
const source=html.slice(a,b);
const sandbox={APP,console,Math,Date,Number,Object,Array,Map,Set};
vm.createContext(sandbox);
vm.runInContext(source,sandbox);
assert.equal(typeof sandbox.auditGates,"function");
assert.equal(APP.weeks.length,36);assert.equal(APP.passingTarget,80);
assert.equal(APP.majorAssessments.length,13);assert.equal(APP.capstoneCheckpoints.length,10);
const s={id:"fictional-senior",progress:{weeks:{},assessments:{},capstones:{},thesis:{words:4500,score:90,defense:90,integrity:true,evaluator:true,hours:150},exams:{semester:{best:90},final:{best:90}},creditIssued:false}};
for(const w of APP.weeks)s.progress.weeks[w.week]={lessons:{},assignments:{},notes:{},quiz:{best:90,attempts:[]},portfolio:true};
for(const a of APP.majorAssessments)s.progress.assessments[a.id]=90;
for(const c of APP.capstoneCheckpoints)s.progress.capstones[c.id]=true;
const baseline=sandbox.auditGates(s);assert.equal(baseline.length,13);
assert.equal(baseline.filter(g=>!g[1]).length>0,true,"Lessons and assignments must remain required");
assert.equal(sandbox.readyForCredit(s),false);
s.progress.thesis.evaluator=false;
assert.equal(sandbox.auditGates(s).find(g=>g[0].startsWith("Integrity"))[1],false);
s.progress.thesis.evaluator=true;
s.progress.exams.final.best=79;
assert.equal(sandbox.auditGates(s).find(g=>g[0].startsWith("Cumulative final"))[1],false);
s.progress.exams.final.best=90;
s.progress.weeks[17].quiz.best=79;
assert.equal(sandbox.auditGates(s).find(g=>g[0].startsWith("All 36 quizzes"))[1],false);
console.log("PASS: course gates enforce weekly mastery, final, evaluator; incomplete lessons and assignments remain locked");
